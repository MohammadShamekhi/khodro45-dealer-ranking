def _build_model_title_to_ids(rows: list[dict]) -> dict[str, list[int]]:
    title_to_ids: dict[str, set[int]] = {}
    for row in rows:
        title_to_ids.setdefault(row["model_title"], set()).add(row["model_id"])
    return {title: sorted(ids) for title, ids in title_to_ids.items()}


def _build_model_id_to_brand_model(rows: list[dict]) -> dict[int, str]:
    return {
        row["model_id"]: f'{row["brand_title"]} {row["model_title"]}'
        for row in rows
    }


